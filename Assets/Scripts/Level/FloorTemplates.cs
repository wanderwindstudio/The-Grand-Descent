using UnityEngine;

// A floor layout drawn as text. Each character is one cell (cellSize metres, see TuningConfig).
//   #  wall          .  floor
//   P  player start  S  goblin spawn point
//   H  pipe shrine spot (off the main path / risky places)
//   O  where the portals open
//   T  wall with a torch on it (the torch faces the neighbouring floor)
// Top of the text is north. Edit these or add new ones; one is picked at random per floor.
public class FloorTemplate
{
    public readonly string name;
    public readonly string[] rows;

    public FloorTemplate(string name, string[] rows)
    {
        this.name = name;
        this.rows = rows;
    }
}

